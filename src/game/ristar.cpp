// ---- releases ----------------------------------------------------------------------------------------------------
struct Site { uint32_t us, here; };
struct Rev {
    const char* label;
    const Site* sites;          // USA address -> this release's, ascending (null: the same addresses)
    size_t      count;
    uint32_t at(uint32_t a) const {
        if (!sites) return a;
        const Site* end = sites + count;
        const Site* s = std::lower_bound(sites, end, a, [](const Site& x, uint32_t v) { return x.us < v; });
        return s != end && s->us == a ? s->here : 0;
    }
};
