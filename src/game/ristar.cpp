// Ristar (Sega Mega Drive / Genesis, 1995): the USA / Europe cartridge and the Japanese one ("Ristar - The Shooting
// Star"). ROM identification for the launcher (one card, either release, a prompt when both are there), and the
// widescreen view for both. The notes, with the addresses and how they were found, are in docs/WIDESCREEN.md.
//
// How the wide view works:
//  * The renderer draws `ext` more columns on each side of the 320-px picture (40 = 16:9, 20 = 16:10).
//  * The game keeps its 512-px planes filled from the camera's left edge on (camera X .. +512). PC hooks in its
//    column / row / whole-plane drawing move that window W = 80 px left, so the plane has the map on both sides.
//  * The view never leaves the map: next to a map end it leans the other way (VDP::view_shift) instead of showing
//    what is outside, so the game's own camera, and with it the gameplay, are untouched. The map's ends are read from
//    the level layout, not from the camera limits: a boss arena's locked camera still gets its full wide picture.
//  * Objects: the window they are drawn in, the "is it on screen" test and the distance at which the object list
//    creates them all grow with the view (three patched immediates, hooks on the list's reach).
//  * The HUD (score, stars, lives) moves out to the screen edges; title, menus and story scenes stay 4:3.
//
// All ROM addresses below are the USA / Europe release's. The Japanese release is the same program a little further
// up or down: Rev::at() gives its address (table made and checked by tools/re/ristar_sites.py). The RAM is the same.
// The ROM is never kept or shipped: patches and hooks apply in memory to the player's own dump, and in 4:3 the dump
// runs as it is.
